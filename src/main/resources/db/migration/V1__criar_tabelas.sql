CREATE TABLE cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL
);

CREATE TABLE produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(255),
    preco_atual NUMERIC(10, 2) NOT NULL,
    desconto_percentual NUMERIC(5, 2) NOT NULL DEFAULT 0,

    CONSTRAINT ck_produto_preco
        CHECK (preco_atual >= 0),

    CONSTRAINT ck_produto_desconto
        CHECK (desconto_percentual BETWEEN 0 AND 100)
);

CREATE TABLE pedido(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    subtotal NUMERIC(19, 2) NOT NULL,
    desconto_total NUMERIC(19, 2) NOT NULL,
    valor_total NUMERIC(19, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_pedido_cliente
        FOREIGN KEY (cliente_id) REFERENCES cliente(id),
    
    CONSTRAINT ck_pedido_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT ck_pedido_desconto
        CHECK (desconto_total BETWEEN 0 AND subtotal),

    CONSTRAINT ck_pedido_valor_total
        CHECK (valor_total = subtotal - desconto_total),

    CONSTRAINT ck_pedido_status
        CHECK (status IN (
            'CRIADO',
            'PROCESSANDO',
            'FATURADO',
            'CANCELADO'
        ))
);


CREATE TABLE item_pedido(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10, 2) NOT NULL,
    desconto_percentual NUMERIC(5, 2) NOT NULL,
    desconto NUMERIC(19, 2) NOT NULL,
    valor_total NUMERIC(19, 2) NOT NULL,

    CONSTRAINT fk_item_pedido
        FOREIGN KEY (pedido_id) REFERENCES pedido(id),

    CONSTRAINT fk_item_produto
        FOREIGN KEY (produto_id) REFERENCES produto(id),
    
    CONSTRAINT ck_pedido_quantidade
        CHECK (quantidade > 0),

    CONSTRAINT ck_preco_unitario
        CHECK (preco_unitario >= 0),
    
    CONSTRAINT ck_item_desconto
        CHECK (desconto_percentual BETWEEN 0 AND 100),

    CONSTRAINT ck_item_valor_total
        CHECK (valor_total = preco_unitario * quantidade - desconto),

    CONSTRAINT ck_item_desconto_valor
        CHECK (desconto BETWEEN 0 AND preco_unitario * quantidade)
);

CREATE TABLE request(
    request_id VARCHAR(100) PRIMARY KEY,
    request_hash VARCHAR(64) NOT NULL,
    pedido_id BIGINT,
    status VARCHAR(20) NOT NULL,

    CONSTRAINT fk_request_pedido
        FOREIGN KEY (pedido_id) REFERENCES pedido(id),

    CONSTRAINT ck_request_pedido
        CHECK(
            (status = 'PROCESSANDO' AND pedido_id IS NULL) OR
            (status = 'CONCLUIDO' AND pedido_id IS NOT NULL)
        )
)